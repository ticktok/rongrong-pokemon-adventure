import {writeFile,mkdir} from 'node:fs/promises';
import {randomUUID} from 'node:crypto';
import {gzipSync} from 'node:zlib';
import {parseArgs} from 'node:util';
import {loadOps,settings} from './ops-lib.mjs';
const {values}=parseArgs({options:{reason:{type:'string',default:'manual'}}});
const {BackupStore}=await loadOps(),{envId,version,apiKey}=await settings();
if(!['manual','release'].includes(values.reason))throw new Error('Use --reason manual or release');
const store=new BackupStore(envId,apiKey),backup=await store.snapshot(version,values.reason);
await mkdir('private/backups',{recursive:true});
const file='private/backups/snapshot-'+new Date().toISOString().replaceAll(':','-')+'-'+randomUUID()+'.json.gz';
await writeFile(file,gzipSync(JSON.stringify(backup)),{mode:0o600,flag:'wx'});
const receipt={...await store.uploadVerified(backup),file,envId,appVersion:version};
await writeFile('private/backups/latest-receipt.json',JSON.stringify(receipt,null,2),{mode:0o600});
console.log(JSON.stringify(receipt,null,2));
