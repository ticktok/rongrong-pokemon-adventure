import {describe,it,expect} from 'vitest';
import {randomUUID} from 'node:crypto';
import {initialState,makePartner,grant} from '../server/state';
import {execute} from '../server/engine';
import {recordGrowth} from '../server/growth';
import {MOVES} from '../content/world';
import {MOVE_VISUALS} from '../src/game/move-effects';
import {validateSave} from '../server/save-validation';
import type {GameState,Role} from '../src/game/types';
const rt={now:new Date('2026-11-14T10:00:00Z'),uuid:randomUUID,random:()=>.3};
const act=(s:GameState,type:string,payload:Record<string,unknown>={},role:Role='child',now=rt.now)=>execute(s,{type,payload,operationId:randomUUID()},role,{...rt,now});
const fresh=()=>act(initialState([],rt.now),'starter',{speciesId:4}).state;
function solve(s:GameState,correct=true){return act(s,'answer',{questionId:s.question!.id,optionId:correct?s.question!.correctOptionId:s.question!.options.find(o=>o.id!==s.question!.correctOptionId)!.id});}
function battle(){const s=act(fresh(),'encounter').state;Object.assign(s.battle!,{enemy:10,enemyHp:1000,enemyMaxHp:1000});return s;}
describe('persistent growth',()=>{
 it('does not invent legacy or newly acquired progress',()=>{const s=fresh();expect(act(s,'bootstrap').state.growth).toBeUndefined();});
 it('records per-partner delivered experience, levels and evolution without counting deferred rewards',()=>{
  const s=fresh();s.partners.push(makePartner(7,5,rt));s.team=s.partners.map(p=>p.id);const after=structuredClone(s);grant(after,500);recordGrowth(s,after,rt.now.toISOString());
  expect(after.growth!.entries.map(e=>e.toExp-e.fromExp)).toEqual([160,160]);expect(after.carry).toBe(180);validateSave(after);
  const first=after.growth!.lastSeq;const next=act(after,'bootstrap',{},'child',new Date('2026-11-15T10:00:00Z')).state;
  expect(next.growth!.entries.slice(first).map(e=>e.toExp-e.fromExp)).toEqual([90,90]);
  const high=fresh();high.partners[0].exp=2250;high.partners[0].level=16;
  const evolved=act(high,'evolve',{partnerId:high.partners[0].id,speciesId:5}).state;
  expect(evolved.growth!.entries[0]).toMatchObject({fromSpecies:4,toSpecies:5,fromLevel:16,toLevel:16,fromExp:2250,toExp:2250});
 });
 it('preserves future entries, rejects parent acknowledgement and keeps read history bounded',()=>{
  let s=fresh();for(let i=0;i<100;i++){const next=structuredClone(s);next.partners[0].exp++;recordGrowth(s,next,rt.now.toISOString());s=next;}
  expect(s.growth!.entries).toHaveLength(100);
  expect(()=>act(s,'growth.ack',{through:95},'parent')).toThrow('训练师');
  expect(()=>act(s,'growth.ack',{through:101})).toThrow('更新');
  s=act(s,'growth.ack',{through:95}).state;expect(s.growth!.entries).toHaveLength(85);expect(s.growth!.readThrough).toBe(95);
  s=act(s,'growth.ack',{through:90}).state;expect(s.growth!.readThrough).toBe(95);expect(s.growth!.entries.filter(e=>e.seq>95)).toHaveLength(5);
  validateSave(s);
 });
 it('does not acknowledge rollover growth generated by the acknowledgement itself',()=>{
  const s=fresh(),next=structuredClone(s);grant(next,500);recordGrowth(s,next,rt.now.toISOString());
  const after=act(next,'growth.ack',{through:1},'child',new Date('2026-11-15T10:00:00Z')).state;
  expect(after.growth!.readThrough).toBe(1);expect(after.growth!.lastSeq).toBe(2);
 });
 it('captures offline parent approval and full-level overflow accurately',()=>{
  let s=fresh();s=act(s,'checkin.submit',{taskIds:s.settings.tasks.map(t=>t.id)}).state;
  s=act(s,'parent.review',{date:s.daily.date,approve:true},'parent').state;
  expect(s.growth!.readThrough).toBe(0);expect(s.growth!.entries[0].toExp-s.growth!.entries[0].fromExp).toBe(230);
  const before=structuredClone(s);s.partners[0].exp=24010;s.partners[0].level=50;delete s.growth;
  const capped=structuredClone(s);grant(capped,100);recordGrowth(s,capped,rt.now.toISOString());expect(capped.growth).toBeUndefined();expect(before.partners[0].level).toBeGreaterThan(5);
 });
});
describe('authoritative battle events',()=>{
 it('covers every shipped move with an intentional visual',()=>{expect(Object.keys(MOVE_VISUALS).sort()).toEqual(MOVES.map(m=>m.id).sort());expect(new Set(Object.values(MOVE_VISUALS).map(v=>v.shape)).size).toBeGreaterThan(25);});
 it('emits actual moves in order with HP snapshots and no event for a wrong answer',()=>{
  let s=act(battle(),'battle.move',{moveId:'fire-0'}).state;
  const wrong=solve(s,false);expect(wrong.result.battlePlayback).toBeUndefined();s=wrong.state;
  const r=solve(s),events=r.result.battlePlayback!.events,attacks=events.filter(e=>e.kind==='attack');
  expect(attacks.map(e=>e.side)).toEqual(['own','enemy']);expect(attacks[0]).toMatchObject({moveId:'fire-0',bonus:1,effectiveness:2});
  expect(attacks[0].before.battle.enemyHp-attacks[0].after.battle.enemyHp).toBe(attacks[0].damage);
  expect(attacks[1].after.battle.playerHp).toBe(r.state.battle!.playerHp);
 });
 it('emits no enemy counterattack after knockout and orders gym replacement after faint',()=>{
  let s=battle();s.battle!.enemyHp=1;s=act(s,'battle.move',{moveId:'fire-0'}).state;
  expect(solve(s).result.battlePlayback!.events.map(e=>e.kind)).toEqual(['attack','faint','outcome']);
  s=battle();Object.assign(s.battle!,{enemyHp:1,enemies:[10,13]});s=act(s,'battle.move',{moveId:'fire-0'}).state;
  const r=solve(s);expect(r.result.battlePlayback!.events.map(e=>e.kind)).toEqual(['attack','faint','sendout']);expect(r.result.battlePlayback!.events.at(-1)!.after.battle.enemy).toBe(13);
 });
 it('preserves the fainted player snapshot before automatic replacement',()=>{
  let s=battle();const next=makePartner(7,5,rt);s.partners.push(next);s.team.push(next.id);s.battle!.teamHp[next.id]=30;s.battle!.playerHp=1;s.battle!.teamHp[s.battle!.playerId]=1;
  s=act(s,'battle.move',{moveId:'normal-0'}).state;const r=solve(s),events=r.result.battlePlayback!.events;
  expect(events.map(e=>e.kind)).toEqual(['attack','attack','faint','sendout']);expect(events[1].after.battle.playerHp).toBe(0);expect(events[1].after.playerSpecies).toBe(4);expect(events[3].after.playerSpecies).toBe(7);
 });
 it('keeps immune damage at zero and first-answer bonus in the event',()=>{
  let s=battle();s.battle!.enemy=92;s=act(s,'battle.move',{moveId:'normal-0'}).state;
  expect(solve(s).result.battlePlayback!.events[0]).toMatchObject({kind:'attack',damage:0,effectiveness:0,bonus:1.25});
 });
 it('plays failed capture before counterattack, with no imaginary player attack',()=>{
  let s=battle();s.battle!.enemy=150;s.battle!.enemyLevel=50;s=act(s,'battle.catch').state;
  const r=execute(s,{type:'answer',operationId:randomUUID(),payload:{questionId:s.question!.id,optionId:s.question!.correctOptionId}},'child',{...rt,random:()=>.999});
  expect(r.result.battlePlayback!.events[0].kind).toBe('capture');expect(r.result.battlePlayback!.events.filter(e=>e.kind==='attack').map(e=>e.side)).toEqual(['enemy']);
 });
});
